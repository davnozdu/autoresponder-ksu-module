#!/system/bin/sh
# Сторож своей записи звонка (pal_record). Запускается из answermachine.sh на каждый recstart.
#
# Буфер записи лежит в ОЗУ (tmpfs моста) и может занимать до ~2 ГБ. Освобождает его
# приложение: recsave (перенос на диск) или recdiscard (стереть). Если приложение упало,
# было убито или споткнулось посреди сценария, ни того ни другого не придёт, и буфер
# висел бы в памяти до следующего звонка или перезагрузки, а запись шла бы до своего
# потолка. Сторож закрывает этот класс отказов, ничего не теряя:
#   1) звонка нет уже минуту, а запись идёт — останавливает её сам (через стоп-файл,
#      чтобы pal_record дописал WAV-заголовок);
#   2) запись остановлена, а буфер никто не забрал за 10 минут — переносит его на диск
#      (rescued/, приложение подхватывает оттуда в журнал) и освобождает ОЗУ.
# Новый recstart перезаписывает файл сессии — прежний сторож видит это и тихо выходит.
#
# Аргументы: <pid pal_record> <wav> <стоп-файл> <файл сессии> <лог> <папка спасения> <штамп yyMMddHHmm>

RPID=$1; W=$2; RECSTOPF=$3; SESSF=$4; LOG=$5; RESCUE=$6; STAMP=$7

log() { echo "$(date '+%Y-%m-%d %H:%M:%S') rec_guard[$RPID]: $*" >> "$LOG" 2>/dev/null; }
mine() { [ "$(cat "$SESSF" 2>/dev/null)" = "$RPID" ]; }
# mCallState: 0 — нет звонка, 1 — звонит, 2 — разговор (по строке на каждую SIM).
# Возвращает 0 — идёт, 1 — не идёт, 2 — не смогли узнать. Пустой или незнакомый вывод — это
# НЕ «звонка нет»: раньше смена формата dumpsys в прошивке приводила к обрыву записи
# живого разговора через минуту. Неизвестность трактуем как «звонок идёт» (fail-open) —
# буфер всё равно ограничен max_sec у pal_record.
call_state() {
  _d=$(dumpsys telephony.registry 2>/dev/null)
  case "$_d" in *mCallState=*) : ;; *) return 2 ;; esac
  echo "$_d" | grep -q 'mCallState=[12]' && return 0
  return 1
}

# 1) Запись идёт — ждём конца звонка плюс минуту на штатный recstop от приложения.
idle=0
while [ -d "/proc/$RPID" ]; do
  mine || exit 0
  call_state; case $? in 0) idle=0 ;; 1) idle=$((idle + 1)) ;; *) idle=0 ;; esac
  if [ "$idle" -ge 4 ]; then                          # 4 × 15с без звонка
    log "звонка нет уже минуту, recstop не пришёл — останавливаю запись сам"
    touch "$RECSTOPF" 2>/dev/null
    break
  fi
  sleep 15
done
i=0
while [ -d "/proc/$RPID" ] && [ "$i" -lt 20 ]; do sleep 1; i=$((i + 1)); done

# 2) Запись остановлена — даём приложению 10 минут на recsave/recdiscard.
i=0
while [ -f "$W" ] && [ "$i" -lt 40 ]; do
  mine || exit 0
  sleep 15; i=$((i + 1))
done
[ -f "$W" ] || exit 0
mine || exit 0

# 3) Буфер так никто и не забрал — на диск, ОЗУ освобождаем. Флеш недоступен — ещё
# несколько попыток, затем всё равно освобождаем память: держать 2 ГБ ОЗУ вечно хуже.
mkdir -p "$RESCUE" 2>/dev/null
dst="$RESCUE/own-recording-$STAMP.wav"
n=0
while [ "$n" -lt 4 ]; do
  mine || exit 0
  if cp -f "$W" "$dst" 2>/dev/null; then
    rm -f "$W"
    log "буфер не забрали 10 мин — спасён на диск: $dst, ОЗУ освобождена"
    exit 0
  fi
  n=$((n + 1)); sleep 300
done
rm -f "$W" "$dst"
log "буфер не удалось перенести на диск ($dst) — удалён, ОЗУ освобождена"
