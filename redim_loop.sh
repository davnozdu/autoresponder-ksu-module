#!/system/bin/sh
# redim_loop.sh — локальный цикл переустановки подсветки в 0, пока активна блокировка
# экрана (см. blockon в answermachine.sh). Раньше тот же тик гонялся через IPC: приложение
# слало команду redim файлом req каждые 30мс, демон отвечал в resp с chown+chcon на каждый
# ответ, писал строку в лог — до ~33 файловых цикла в секунду на весь звонок. Сам тик в
# 30мс — не с потолка: DisplayManager перебивает подсветку через пару секунд, а более
# редкий тик (проверялось 3000мс на реальном звонке) делает системные вспышки экрана на
# ответе/отбое (PROXIMITY_SCREEN_OFF_WAKE_LOCK у com.android.incallui, не наш код) заметными
# глазом — сам тик трогать нельзя, убираем только IPC вокруг него.
#
# Отдельный файл через nohup, тот же приём, что у watchdog_block.sh — тот же STOPF глушит
# оба цикла разом (blockoff просто touch'ит его один раз).
STOPF="$1"; BL="$2"
while [ ! -f "$STOPF" ]; do
  [ -n "$BL" ] && echo 0 > "$BL" 2>/dev/null
  sleep 0.03
done
