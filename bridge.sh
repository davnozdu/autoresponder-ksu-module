#!/system/bin/sh
# bridge.sh — root-мост к базам мессенджеров.
#
# Приложение видит переписку WhatsApp и Telegram только через уведомления, а значит
# не видит ничего, что уведомления не показали: сообщения, которые владелец набрал
# сам в мессенджере, входящие при выключенном роботе, всё старше пяти минут. Из-за
# этого в контекст LLM уходил односторонний монолог клиента, и робот отвечал по
# кругу одно и то же.
#
# Настоящая переписка лежит в базах самих мессенджеров, но они под чужим uid и с
# правами 0600 — приложению их не открыть. Root есть у модуля, поэтому копирование
# делает он, а разбор схемы остаётся в приложении: схему WhatsApp и TL-блобы
# Telegram в shell не разобрать, а в Kotlin это тестируется.
#
# Протокол (весь внутри приватной папки приложения — на /sdcard переписка клиентов
# была бы видна любому приложению с доступом к хранилищу):
#   files/bridge/request   приложение пишет "<epoch>"            -> обычный прогон
#                          или        "<epoch> <метки через пробел>" -> адресный
#   files/bridge/<db>      копии баз (db + -wal), chown и метка SELinux приложения
#   files/bridge/response  строка "<epoch> ok|partial|none <детали>"
#
# Ждём запрос через inotifyd — без опроса, то есть без расхода батареи. Плюс
# принудительный прогон по таймеру: если приложение убито, копии всё равно свежие.
#
# --- О РАСХОДЕ ФЛЕША ---------------------------------------------------------
# Копии — это сотни мегабайт (у Telegram одна cache4.db под 156 МБ), и раньше все
# базы переписывались целиком на каждый прогон, то есть примерно 26 ГБ записи в
# сутки ради нескольких новых сообщений. Против этого здесь три вещи:
#
#   1) копии лежат в ОЗУ (tmpfs поверх папки приложения) — на флеш не пишется ничего;
#   2) файл копируется, только если у источника изменились размер или mtime;
#   3) тяжёлые базы «по требованию» (см. ONDEMAND) в обычный прогон не попадают.
#
# Копия одноразовая: пропала при перезагрузке — снимется заново при первом прогоне,
# который идёт сразу после старта модуля.

MODDIR=${0%/*}
PKG=com.davnozdu.autoresponder
DIR=/data/data/$PKG/files/bridge
REQ=$DIR/request
RESP=$DIR/response
LOG="$MODDIR/bridge.log"

# Потолок tmpfs. Это ВЕРХНЯЯ граница, а не занятая память: tmpfs берёт ровно столько,
# сколько лежит внутри (сейчас около 180 МБ при 15 ГБ ОЗУ).
RAM_SIZE=512M

# Не чаще одного ОБЫЧНОГО прогона в MIN_GAP секунд: приложение просит обновление перед
# каждым ответом, а клиент в переписке пишет очередями по несколько сообщений.
# Адресная просьба этим не ограничена: её шлют, когда копия нужна прямо сейчас.
MIN_GAP=60
# Принудительный прогон, даже если никто не просил (приложение может быть убито).
# Раз в час: приложение и само просит не чаще, а копируется теперь только изменившееся,
# так что лишний прогон почти ничего не стоит.
FORCE_EVERY=3600

# Базы: <метка> <путь>. Метка = имя подпапки в bridge/ и канал в журнале.
DBS="whatsapp:/data/data/com.whatsapp.w4b/databases/msgstore.db
whatsapp2:/data/data/com.whatsapp/databases/msgstore.db
telegram:/data/data/org.telegram.messenger/files/cache4.db
rcs:/data/data/com.google.android.apps.messaging/databases/bugle_db"

# Метки «по требованию»: в обычный прогон НЕ попадают, копия делается, только когда
# приложение попросит именно их, и стирается на следующем обычном прогоне.
#
# Google Messages (метка rcs) нужен не ради переписки, а ради ОДНОГО поля: номера
# отправителя. По RCS клиент приходит под именем и аватаром своего профиля, и в
# уведомлении номера нет вообще. Случай редкий — держать ради него 17 МБ копии
# постоянно и обновлять по таймеру незачем.
ONDEMAND="rcs"

log() { echo "$(date '+%m-%d %H:%M:%S') $*" >> "$LOG"; }
trim() { tail -n 300 "$LOG" > "$LOG.t" 2>/dev/null && mv "$LOG.t" "$LOG"; }

in_list() {
  for _w in $2; do [ "$_w" = "$1" ] && return 0; done
  return 1
}

app_uid() {
  # stat приватной папки — единственный способ, не зависящий от формата dumpsys.
  stat -c %u "/data/data/$PKG/files" 2>/dev/null
}

# SELinux-метка приватной папки приложения. Метка несёт категории конкретного
# приложения (`...:s0:c27,c257,c512,c768`), и без них приложение не откроет даже
# собственный файл. restorecon эти категории не восстанавливает — он ставит
# политику по умолчанию, то есть голый s0, — поэтому копируем метку с папки.
# Читаем каждый раз: после переустановки приложения категории другие.
app_ctx() { ls -dZ "/data/data/$PKG/files" 2>/dev/null | awk '{print $1}'; }
relabel() {
  ctx=$(app_ctx)
  [ -n "$ctx" ] || return 0
  chcon -R "$ctx" "$@" 2>/dev/null
}

# --- копии в ОЗУ -------------------------------------------------------------
#
# tmpfs монтируется из глобального пространства монтирования (модуль стартует от init),
# а у приложения /data помечен `master:` — то есть slave, и новый маунт до него
# доезжает даже если процесс уже запущен. Метка SELinux с категориями приложения на
# tmpfs держится, проверено на устройстве.
#
# Не смонтировалось — не беда: работаем как раньше, по диску. Ради экономии флеша
# ломать мост нельзя, без моста робот отвечает без контекста переписки.
is_tmpfs() {
  awk -v d="$1" '$5==d && index($0," - tmpfs ")>0 {found=1} END{exit !found}' \
    /proc/self/mountinfo 2>/dev/null
}

ensure_ram() {
  is_tmpfs "$DIR" && return 0
  mkdir -p "$DIR" 2>/dev/null || return 1
  # Копии от прошлых версий модуля лежат на флеше. Стереть их надо ДО монтирования:
  # после него старые файлы останутся под маунтом, невидимые и занятые навсегда.
  for _e in $DBS; do
    _t=${_e%%:*}
    [ -d "$DIR/$_t" ] && { rm -rf "$DIR/$_t" 2>/dev/null; log "старая копия $_t убрана с диска"; }
  done
  if mount -t tmpfs -o "size=$RAM_SIZE,mode=700" autoresp_bridge "$DIR" 2>/dev/null; then
    log "копии переведены в ОЗУ (tmpfs $RAM_SIZE)"
    return 0
  fi
  log "tmpfs не смонтирован — копии остаются на диске"
  return 1
}

# Отпечаток файла: размер и время изменения. Снимаем ДО копирования — если источник
# изменится во время копии, отпечаток останется старым и в следующий раз мы скопируем
# заново. Ошибаться безопаснее в эту сторону.
fingerprint() { stat -c '%s:%Y' "$1" 2>/dev/null || echo "-"; }

# 0 — скопировали, 1 — не потребовалось, 2 — не вышло.
copy_file() {
  src=$1; dstf=$2; stampf=$3
  fp=$(fingerprint "$src")
  if [ -f "$dstf" ] && [ "$fp" = "$(cat "$stampf" 2>/dev/null)" ]; then return 1; fi
  cp -f "$src" "$dstf" 2>/dev/null || return 2
  echo "$fp" > "$stampf"
  return 0
}

# Копия одной базы вместе с -wal. Без -wal копия неполна: свежие сообщения лежат
# именно там, а checkpoint мессенджер делает когда захочет.
#
# Порядок важен: сначала сама база, потом -wal. Если между копированиями мессенджер
# сделает checkpoint, в -wal окажутся кадры, уже применённые к базе, — это SQLite
# переживает. Обратный порядок дал бы -wal старее базы, то есть испорченную копию.
#
# Пофайловая проверка отпечатка тут и экономит: в режиме WAL большая база
# переписывается только на checkpoint. У WhatsApp msgstore.db не менялась по девять
# часов подряд, а копировалась все эти часы каждые десять минут.
#
# -shm НЕ копируем и остаток от прошлого раза удаляем: это разделяемая память живой
# базы, к чужому снимку она не подходит, а SQLite соберёт её заново сам.
copy_db() {
  tag=$1; src=$2; uid=$3
  CHANGED=0
  [ -f "$src" ] || return 1
  dst="$DIR/$tag"
  mkdir -p "$dst" || return 1
  base=$(basename "$src")
  rm -f "$dst/$base-shm" 2>/dev/null

  # Старый WAL относится к предыдущему снимку. Если источник уже сделал
  # checkpoint и собственного WAL больше нет, оставшийся файл нельзя оставлять:
  # SQLite применит его к новой базе и вернёт старые страницы.
  has_wal=0
  [ -f "$src-wal" ] && has_wal=1

  copy_file "$src" "$dst/$base" "$MODDIR/.src-$tag"
  case $? in 2) return 1 ;; 0) CHANGED=1 ;; esac
  if [ "$has_wal" = "1" ]; then
    copy_file "$src-wal" "$dst/$base-wal" "$MODDIR/.src-$tag-wal"
    case $? in 2) return 1 ;; 0) CHANGED=1 ;; esac
  else
    rm -f "$dst/$base-wal" "$MODDIR/.src-$tag-wal" 2>/dev/null
  fi

  # Ничего не писали — значит и владельца с меткой менять не на чем.
  [ "$CHANGED" = "1" ] || return 0

  chown -R "$uid:$uid" "$dst" 2>/dev/null
  chmod -R 600 "$dst"/* 2>/dev/null
  chmod 700 "$dst" 2>/dev/null
  # Без метки приложения у копий остаётся контекст источника, и SELinux не даст
  # приложению открыть файл в собственной папке.
  relabel "$dst"
  return 0
}

# Убрать копию «по требованию»: она нужна ровно на время одного разбирательства.
drop_copy() {
  [ -d "$DIR/$1" ] || return 0
  rm -rf "$DIR/$1" 2>/dev/null
  rm -f "$MODDIR/.src-$1" "$MODDIR/.src-$1-wal" 2>/dev/null
  log "копия $1 больше не нужна — убрана"
}

# $1 — метки, которые просили (пусто = обычный прогон).
sync_all() {
  want=$1
  uid=$(app_uid)
  if [ -z "$uid" ]; then log "нет uid приложения — пропуск"; return 1; fi
  ok=0; fail=0; names=""; wrote=""
  for entry in $DBS; do
    tag=${entry%%:*}; src=${entry#*:}
    if [ -n "$want" ]; then
      in_list "$tag" "$want" || continue
    elif in_list "$tag" "$ONDEMAND"; then
      drop_copy "$tag"
      continue
    fi
    # Мессенджера может просто не быть на телефоне (обычный WhatsApp против
    # WhatsApp Business) — это не сбой, а отсутствие источника.
    [ -f "$src" ] || continue
    if copy_db "$tag" "$src" "$uid"; then
      ok=$((ok+1)); names="$names $tag"
      [ "$CHANGED" = "1" ] && wrote="$wrote $tag"
    else
      fail=$((fail+1)); log "не скопировалось: $tag ($src)"
    fi
  done
  if [ "$ok" = "0" ]; then status=none
  elif [ "$fail" = "0" ]; then status=ok
  else status=partial
  fi
  echo "$(date +%s) $status$names" > "$RESP"
  chown "$uid:$uid" "$RESP" 2>/dev/null; chmod 600 "$RESP" 2>/dev/null
  relabel "$RESP"
  log "sync $status:$names (записано:${wrote:- ничего})"
  return 0
}

# Отметка последнего копирования — в файле, а не в переменной: ветка inotifyd
# живёт в подоболочке, и присвоение в ней до остальных не доходит.
STAMP=$MODDIR/.bridge-stamp
# Пустой или испорченный файл отметки должен читаться как «никогда», иначе
# арифметика ниже падает и мост перестаёт копировать вовсе.
last_sync() {
  v=$(cat "$STAMP" 2>/dev/null)
  case "$v" in ''|*[!0-9]*) echo 0 ;; *) echo "$v" ;; esac
}

handle() {
  now=$(date +%s)
  # Приложение может назвать нужные ему метки вторым полем: "<epoch> rcs".
  # Пустой список = обычный прогон. Старое приложение пишет одно число — оно и
  # попадёт в обычный прогон, то есть совместимость сохраняется.
  req=$(head -c 200 "$REQ" 2>/dev/null | tr -d '\n\r')
  case "$req" in
    *\ *) want=${req#* } ;;
    *)    want="" ;;
  esac
  if [ -z "$want" ]; then
    if [ $((now - $(last_sync))) -lt "$MIN_GAP" ]; then return 0; fi
    echo "$now" > "$STAMP"
  fi
  sync_all "$want"
  trim
}

# Папку и файл-запрос создаём сами: приложение могло ещё ни разу не запуститься,
# а inotifyd без существующего файла просто выходит.
prepare() {
  uid=$(app_uid)
  [ -n "$uid" ] || return 1
  mkdir -p "$DIR" || return 1
  chown "$uid:$uid" "$DIR"; chmod 700 "$DIR"
  [ -f "$REQ" ] || : > "$REQ"
  chown "$uid:$uid" "$REQ"; chmod 600 "$REQ"
  relabel "$DIR"
  return 0
}

# --- старт ---------------------------------------------------------------
: > "$LOG"; log "bridge start (pid $$)"

# Таймер в фоне — трогает request, чем будит ту же ветку, что и приложение.
# Нужен на случай, когда приложение убито: копии всё равно остаются свежими.
(
  while :; do
    sleep "$FORCE_EVERY"
    [ -f "$REQ" ] && touch "$REQ" 2>/dev/null
  done
) &

# Внешний цикл переживает переустановку приложения: при ней папка files пересоздаётся,
# inotifyd теряет inode и выходит — здесь мы просто заводим наблюдение заново.
while :; do
  if ! app_uid >/dev/null; then
    log "приложение не установлено — ждём"
    sleep 60
    continue
  fi
  # ОЗУ заводим до prepare: request и response должны лежать уже внутри tmpfs,
  # иначе приложение писало бы в файл, который маунт тут же спрячет.
  ensure_ram
  if ! prepare; then
    log "папка приложения недоступна — ждём"
    sleep 60
    continue
  fi
  # Первый прогон сразу: после перезагрузки или переустановки контекст нужен
  # не через час, а сейчас — и копий в ОЗУ после перезагрузки нет вовсе.
  handle
  # Маски: c — записан, e — тронут (touch), w — закрыт после записи.
  # inotifyd вызывается на каждое изменение request и не тратит батарею на опрос.
  inotifyd - "$REQ:cew" 2>/dev/null | while read -r _ev _rest; do
    handle
  done
  log "наблюдение прервано — перезапуск через 30с"
  sleep 30
done
